CREATE DATABASE IF NOT EXISTS tmc_pos CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE tmc_pos;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, full_name VARCHAR(120) NOT NULL, username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('admin','manager','cashier') NOT NULL DEFAULT 'cashier',
 is_active TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS categories (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL UNIQUE, is_active TINYINT(1) NOT NULL DEFAULT 1) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS products (
 id INT AUTO_INCREMENT PRIMARY KEY, category_id INT NOT NULL, name VARCHAR(140) NOT NULL, description VARCHAR(255),
 price DECIMAL(10,2) NOT NULL, is_available TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (category_id) REFERENCES categories(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS stock_items (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(140) NOT NULL UNIQUE, unit VARCHAR(30) NOT NULL,
 quantity_on_hand DECIMAL(12,3) NOT NULL DEFAULT 0, reorder_level DECIMAL(12,3) NOT NULL DEFAULT 0,
 unit_cost DECIMAL(10,2) NOT NULL DEFAULT 0, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS recipes (
 id INT AUTO_INCREMENT PRIMARY KEY, product_id INT NOT NULL UNIQUE,
 FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS recipe_items (
 id INT AUTO_INCREMENT PRIMARY KEY, recipe_id INT NOT NULL, stock_item_id INT NOT NULL, quantity_used DECIMAL(12,3) NOT NULL,
 UNIQUE KEY uq_recipe_stock(recipe_id,stock_item_id), FOREIGN KEY (recipe_id) REFERENCES recipes(id) ON DELETE CASCADE,
 FOREIGN KEY (stock_item_id) REFERENCES stock_items(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cash_shifts (
 id INT AUTO_INCREMENT PRIMARY KEY, cashier_id INT NOT NULL, opening_cash DECIMAL(10,2) NOT NULL DEFAULT 0,
 expected_cash DECIMAL(10,2), closing_cash DECIMAL(10,2), variance DECIMAL(10,2),
 opened_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, closed_at DATETIME,
 status ENUM('open','closed') NOT NULL DEFAULT 'open', FOREIGN KEY (cashier_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sales (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, receipt_number VARCHAR(40) NOT NULL UNIQUE, cashier_id INT NOT NULL,
 shift_id INT NULL, subtotal DECIMAL(10,2) NOT NULL, discount DECIMAL(10,2) NOT NULL DEFAULT 0,
 total DECIMAL(10,2) NOT NULL, status ENUM('completed','voided','refunded') NOT NULL DEFAULT 'completed',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (cashier_id) REFERENCES users(id),
 FOREIGN KEY (shift_id) REFERENCES cash_shifts(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sale_items (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, sale_id BIGINT NOT NULL, product_id INT NULL, product_name VARCHAR(140) NOT NULL,
 quantity DECIMAL(10,2) NOT NULL, unit_price DECIMAL(10,2) NOT NULL, line_total DECIMAL(10,2) NOT NULL,
 FOREIGN KEY (sale_id) REFERENCES sales(id), FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, sale_id BIGINT NOT NULL, method ENUM('cash','ecocash','zipit','card','other') NOT NULL,
 amount DECIMAL(10,2) NOT NULL, reference VARCHAR(100), paid_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (sale_id) REFERENCES sales(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, stock_item_id INT NOT NULL, user_id INT NOT NULL,
 movement_type ENUM('opening','purchase','sale','adjustment','waste','return') NOT NULL,
 quantity_change DECIMAL(12,3) NOT NULL, note VARCHAR(255), created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (stock_item_id) REFERENCES stock_items(id), FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS expenses (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, description VARCHAR(180) NOT NULL,
 amount DECIMAL(10,2) NOT NULL, expense_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id INT NULL, action VARCHAR(100) NOT NULL, details TEXT,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
